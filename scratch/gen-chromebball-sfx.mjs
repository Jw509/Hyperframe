import fs from "fs";
// Build scratch/build-chromebball-sfx.sh — burns the word captions and mixes the SFX onto the
// host's memes+VO export in ONE pass (so the video is encoded once, not twice).
//
// SFX style (memory: sfx_style_approved): swoosh on PACK CHANGES only, cha-ching on each comp
// pop, cost sting once with the tracker entrance, recap SILENT.
const pos = JSON.parse(fs.readFileSync("scratch/chromebball-card-positions.json", "utf8"));
const man = JSON.parse(fs.readFileSync("scratch/chromebball-composite-manifest.json", "utf8"));

const SRC = "cards/sources/chromebball/ChromeBballneedcaption.mp4";
const ASS = "scratch/chromebball-captions.ass";
const OUT = {
  tiktok: "cards/renders/chromebball_final_tiktok.mp4",
  youtube: "cards/renders/chromebball_final_youtube.mp4",
};
const DUR = 110.99;

// Pack changes: each new pack's FIRST card arriving, minus a 0.3s lead so the swoosh pushes the
// card in. These are the cards' ARRIVAL times — for the three fanned pack-openers (edwards,
// chomche, bird) that's the original arrival, NOT the later flat-and-alone chip time.
const PACK_ARRIVE = [11.53, 20.00, 33.13, 43.95, 52.90, 64.10, 73.80, 94.50];
const swooshes = PACK_ARRIVE.map(t => +(t - 0.3).toFixed(2));

// Cha-ching on every comp pop = the chip start times straight out of the manifest.
const chings = man.elements
  .filter(e => e.id.startsWith("cbb-el-chip"))
  .map(e => e.start)
  .sort((a, b) => a - b);

// Cost sting once, with the box-cost tracker entrance.
const sting = man.elements.find(e => e.id === "cbb-el-counter").start;

// Gains calibrated to each file's RAW PEAK (cardswap -24.4 dB, cardmoneysound -32.4 dB,
// packcostsound -16.5 dB). Base calibration lands all three at ~-9 dB; TRIM pulls them down
// together — the host's VO is quiet (mean -40/-35 dB) and -9 dB SFX hit harder than his voice.
const TRIM_DB = -4;                                   // user: "lower the sound a little bit"
const t = 10 ** (TRIM_DB / 20);
const GAIN = { swap: 5.89 * t, money: 14.79 * t, cost: 2.37 * t };

// Red hook banner, baked into the opening of the TIKTOK cut only. It sits in the upper third
// (y 712-1245) and the captions run at y~2300, so they never touch. Built into THIS graph rather
// than as a second pass so the video is still only re-encoded once from the host's export.
// The YOUTUBE cut leaves it out — there the hook is a separate uploaded thumbnail, and having
// both would say the same thing twice.
const HOOK = "scratch/overlay-preview/chromebball_hook_tiktok.png";
const HOOK_OUT = 1.5, HOOK_FADE = 0.25;

// Audio input indices shift by one when the hook PNG is present.
const audioLegs = (base) => {
  const legs = [], labels = ["[0:a]"];
  const push = (srcIdx, gain, times, tag) => {
    const outs = times.map((_, i) => `[${tag}${i}]`);
    legs.push(`[${srcIdx}:a]aformat=sample_rates=48000:channel_layouts=stereo,volume=${gain},asplit=${times.length}${outs.join("")}`);
    times.forEach((t, i) => {
      legs.push(`[${tag}${i}]adelay=delays=${Math.round(t * 1000)}:all=1[${tag}d${i}]`);
      labels.push(`[${tag}d${i}]`);
    });
  };
  push(base, GAIN.swap, swooshes, "sw");
  push(base + 1, GAIN.money, chings, "ch");
  push(base + 2, GAIN.cost, [sting], "st");
  return [...legs, `${labels.join("")}amix=inputs=${labels.length}:normalize=0:duration=first,alimiter=limit=0.95[aout]`];
};

const invocation = (withHook, out) => {
  const video = withHook
    ? [`[1:v]format=rgba,fade=t=out:st=${(HOOK_OUT - HOOK_FADE).toFixed(2)}:d=${HOOK_FADE}:alpha=1[hook]`,
       `[0:v][hook]overlay=0:0:enable='between(t,0,${HOOK_OUT})'[vhook]`,
       `[vhook]subtitles=${ASS}[vout]`]
    : [`[0:v]subtitles=${ASS}[vout]`];
  const graph = [...video, ...audioLegs(withHook ? 2 : 1)].join(";\n      ");
  const hookInput = withHook
    ? `  -loop 1 -framerate 60 -t ${(HOOK_OUT + 0.2).toFixed(2)} -i "${HOOK}" \\\n` : "";
  return `    ffmpeg -y -hide_banner -i "${SRC}" \\
${hookInput}      -i "cards/sounds/cardswap.m4a" \\
      -i "cards/sounds/cardmoneysound.m4a" \\
      -i "cards/sounds/packcostsound.m4a" \\
      -filter_complex "${graph}" \\
      -map "[vout]" -map "[aout]" -t ${DUR} \\
      -c:v hevc_nvenc -preset p5 -rc vbr -cq 19 -b:v 0 -tag:v hvc1 -c:a aac -b:a 256k \\
      "${out}"`;
};

const sh = `#!/usr/bin/env bash
# Burn word captions + mix SFX onto the host's memes/VO export, single encode pass.
# Usage: bash scratch/build-chromebball-sfx.sh [tiktok|youtube|both]
#   tiktok  - red hook banner baked 0-${HOOK_OUT}s (fades over the last ${HOOK_FADE}s)
#   youtube - no baked hook; the hook is the separate uploaded thumbnail instead
# GENERATED by scratch/gen-chromebball-sfx.mjs — edit that, not this.
# ${swooshes.length} swooshes (pack changes) | ${chings.length} cha-chings (comp pops) | 1 cost sting @ ${sting}s | recap silent
set -u
cd "$(dirname "$0")/.." || exit 1
MODE="\${1:-both}"
if [ "$MODE" = "tiktok" ] || [ "$MODE" = "both" ]; then
  echo "=== tiktok (hook baked) ==="
${invocation(true, OUT.tiktok)}
fi
if [ "$MODE" = "youtube" ] || [ "$MODE" = "both" ]; then
  echo "=== youtube (no baked hook) ==="
${invocation(false, OUT.youtube)}
fi
`;
fs.writeFileSync("scratch/build-chromebball-sfx.sh", sh);
console.log(`wrote scratch/build-chromebball-sfx.sh -> ${OUT.tiktok} + ${OUT.youtube}`);
console.log(`swoosh  (${swooshes.length}):`, swooshes.join(" "));
console.log(`chaching(${chings.length}):`, chings.join(" "));
console.log(`sting   (1):`, sting, "| recap @104.28 silent");
