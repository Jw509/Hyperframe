import fs from "fs";
// Build scratch/run-chromebball-composite.sh from the element manifest.
// One ffmpeg pass: source (black-padded for the recap tail) + every alpha element overlaid at its
// timestamp/position, encoded with NVENC. Inactive overlays cost ~nothing thanks to `enable=`.
const m = JSON.parse(fs.readFileSync("scratch/chromebball-composite-manifest.json", "utf8"));
const PAD = +(m.duration - m.videoDur).toFixed(2);   // black tail for the recap

// counter underneath, then chips in time order, recap on top
const order = [
  ...m.elements.filter(e => e.id === "cbb-el-counter"),
  ...m.elements.filter(e => e.id.startsWith("cbb-el-chip")).sort((a, b) => a.start - b.start),
  ...m.elements.filter(e => e.id === "cbb-el-recap"),
];

const inputs = order.map(e => `      -itsoffset ${e.start} -i "cards/renders/${e.file}" \\`).join("\n");
const chain = order.map((e, i) => {
  const src = i === 0 ? "[base]" : `[v${i}]`;
  const end = +(e.start + e.dur).toFixed(2);
  return `      ${src}[${i + 1}:v]overlay=x=${e.x}:y=${e.y}:eof_action=pass:enable='between(t,${e.start},${end})'[v${i + 1}];`;
}).join("\n");
const last = `[v${order.length}]`;

const graph = tail => `"[0:v]tpad=stop_mode=add:stop_duration=${PAD}[base];
${chain}
      ${last}${tail}[vout];
      [0:a]apad=pad_dur=${PAD}[aout]"`;

const run = (out, tail, enc, dur = m.duration) => `    ffmpeg -y -hide_banner -i "${m.video}" \\
${inputs}
      -filter_complex ${graph(tail)} \\
      -map "[vout]" -map "[aout]" -t ${dur.toFixed(2)} \\
      ${enc} \\
      "${out}"`;

const sh = `#!/usr/bin/env bash
# Composite the chromebball overlay elements onto the host's pre-cut.
# Usage: bash scratch/run-chromebball-composite.sh [test|review|final]
#   test   - first 30s at 4K, to eyeball chip placement fast
#   review - full length at 1080p h264, for timing review
#   final  - full length native 2160x3840 hevc, the deliverable
# GENERATED by scratch/gen-chromebball-composite.mjs — edit that, not this.
set -u
cd "$(dirname "$0")/.." || exit 1
MODE="\${1:-review}"
case "$MODE" in
  test)
${run("cards/renders/chromebball_test30.mp4", "format=yuv420p", "-c:v hevc_nvenc -preset p5 -rc vbr -cq 19 -b:v 0 -c:a aac -b:a 256k", 30)}
    ;;
  review)
${run("cards/renders/chromebball_review_1080.mp4", "scale=1080:1920,format=yuv420p", "-c:v h264_nvenc -preset p5 -rc vbr -cq 23 -b:v 0 -c:a aac -b:a 256k")}
    ;;
  final)
${run("cards/renders/chromebball_final_4k60.mp4", "format=yuv420p", "-c:v hevc_nvenc -preset p5 -rc vbr -cq 19 -b:v 0 -c:a aac -b:a 256k")}
    ;;
  *) echo "unknown mode $MODE"; exit 1;;
esac
`;
fs.writeFileSync("scratch/run-chromebball-composite.sh", sh);
console.log(`wrote scratch/run-chromebball-composite.sh — ${order.length} overlays, pad ${PAD}s, out ${m.duration.toFixed(2)}s`);
